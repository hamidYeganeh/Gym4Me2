\getenv migration_password STAGE_MIGRATION_PASSWORD
\getenv runtime_password STAGE_RUNTIME_PASSWORD
CREATE ROLE gym4me_migrator LOGIN PASSWORD :'migration_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
CREATE ROLE gym4me_runtime LOGIN PASSWORD :'runtime_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
ALTER DATABASE gym4me_stage OWNER TO gym4me_migrator;
REVOKE ALL ON DATABASE gym4me_stage FROM PUBLIC;
GRANT CONNECT ON DATABASE gym4me_stage TO gym4me_runtime;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO gym4me_migrator;
GRANT USAGE ON SCHEMA public TO gym4me_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE gym4me_migrator IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO gym4me_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE gym4me_migrator IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO gym4me_runtime;
