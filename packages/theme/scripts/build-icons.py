"""Compile Sandow SVGs to WOFF2, keeping paint order and opacity per glyph.

picosvg resolves strokes, transforms, clips, and even-odd winding before the
TrueType conversion. Committed codepoints stay stable when icons are added.
"""
from pathlib import Path
import json
import re
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path
from picosvg.svg import SVG

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "assets/sandow"
OUTPUT = ROOT / "src/fonts"
MANIFEST = OUTPUT / "sandow-codepoints.json"
UI = ROOT.parent / "ui/src/icons"
EM = 1024


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    UI.mkdir(parents=True, exist_ok=True)
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    used = [code for codes in manifest.values() for code in codes]
    next_code = max(used, default=0xDFFF) + 1
    glyphs = {".notdef": TTGlyphPen(None).glyph()}
    metrics = {".notdef": (EM, 0)}
    cmap = {}
    exports = ['// Generated by @repo/theme icons:build. Do not edit.',
               'import { createSandowIcon } from "../kit/SandowIcon";']
    names = set()
    for source in sorted(SOURCES.glob("*.svg")):
        svg = SVG.parse(str(source)).topicosvg()
        view = svg.view_box()
        assert view is not None and view.w == view.h, source
        layers = []
        codes = manifest.setdefault(source.stem, [])
        for index, shape in enumerate(svg.shapes()):
            if index >= len(codes):
                if next_code > 0xF8FF:
                    raise ValueError("BMP private use area exhausted")
                codes.append(next_code)
                next_code += 1
            code = codes[index]
            name = f"uni{code:04X}"
            pen = TTGlyphPen(None)
            scale = EM / view.w
            transformed = TransformPen(Cu2QuPen(pen, max_err=0.5, reverse_direction=True),
                                       (scale, 0, 0, -scale, -view.x * scale, EM + view.y * scale))
            parse_path(shape.as_path().d, transformed)
            glyph = pen.glyph()
            glyph.recalcBounds(None)
            glyphs[name] = glyph
            metrics[name] = (EM, getattr(glyph, "xMin", 0))
            cmap[code] = name
            layers.append([code, round(shape.opacity * shape.fill_opacity, 4)])
        component = ''.join(part[:1].upper() + part[1:] for part in re.split(r'[^a-zA-Z0-9]+', source.stem)) + "Icon"
        if component[0].isdigit():
            component = "Sandow" + component
        if component in names:
            raise ValueError(f"Duplicate component: {component}")
        names.add(component)
        exports.append(f'export const {component} = createSandowIcon({json.dumps(layers)}, "{component}");')
    font = FontBuilder(EM, isTTF=True)
    font.setupGlyphOrder(list(glyphs))
    font.setupCharacterMap(cmap)
    font.setupGlyf(glyphs)
    font.setupHorizontalMetrics(metrics)
    font.setupHorizontalHeader(ascent=EM, descent=0)
    font.setupNameTable({"familyName": "Sandow Duotone", "styleName": "Regular", "uniqueFontIdentifier": "Gym4Me-Sandow-Duotone-1", "fullName": "Sandow Duotone", "psName": "SandowDuotone", "version": "Version 1.000"})
    font.setupOS2(sTypoAscender=EM, sTypoDescender=0, usWinAscent=EM, usWinDescent=0)
    font.setupPost()
    # Reproducible binary output, independent of the machine/build date.
    font.font.recalcTimestamp = False
    font.font['head'].created = font.font['head'].modified = 2082844800
    font.font.flavor = "woff2"
    font.save(OUTPUT / "sandow-duotone.woff2")
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    (UI / "index.ts").write_text('\n'.join(exports) + '\n')
    print(f"Built {len(names)} icons / {len(cmap)} layers: {OUTPUT / 'sandow-duotone.woff2'}")


if __name__ == '__main__':
    main()
