"""Convert the supplied Freud duotone directory to individual React modules."""

import json
import re
import subprocess
import sys
from pathlib import Path
from xml.etree import ElementTree

NAMESPACE = "{http://www.w3.org/2000/svg}"
SHAPES = {"path", "circle", "rect", "ellipse", "g", "defs", "clipPath"}
ATTRIBUTES = {
    "d", "fill", "fill-opacity", "fill-rule", "clip-rule", "stroke", "stroke-width",
    "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "transform",
    "clip-path", "id",
}
HEADER = "// Generated by scripts/generate.py.\n"


def jsx(element, depth, clip_id):
    tag = element.tag.removeprefix(NAMESPACE)
    if tag not in SHAPES or (element.text or "").strip():
        raise ValueError(f"Unsupported SVG content: {tag}")
    attributes = []
    for name, value in element.attrib.items():
        if name not in ATTRIBUTES:
            raise ValueError(f"Unsupported SVG attribute: {name}")
        prop = re.sub(r"-([a-z])", lambda match: match[1].upper(), name)
        if name == "id" and value == clip_id:
            attribute = "{clipId}"
        elif name == "clip-path" and value == f"url(#{clip_id})":
            attribute = "{`url(#${clipId})`}"
        elif name in {"id", "clip-path"}:
            raise ValueError(f"Unexpected clip reference: {value}")
        else:
            if name in {"fill", "stroke"} and value == "black":
                value = "currentColor"
            attribute = json.dumps(value)
        attributes.append(f" {prop}={attribute}")
    indent = "  " * depth
    opening = f"{indent}<{tag}{''.join(attributes)}"
    if len(element) == 0:
        return f"{opening} />"
    children = "\n".join(jsx(child, depth + 1, clip_id) for child in element)
    return f"{opening}>\n{children}\n{indent}</{tag}>"


def generate(source):
    destination = Path(__file__).resolve().parents[1] / "src"
    modules = {}
    names = set()
    for path in sorted(source.glob("*.svg")):
        slug = re.sub(r"[^a-z0-9]+", "-", path.stem.lower()).strip("-")
        name = "".join(part.capitalize() for part in slug.split("-"))
        if slug in modules or name in names or not re.fullmatch(r"[a-z][a-z0-9-]*", slug):
            raise ValueError(f"Invalid or duplicate export: {path.name}")
        svg = ElementTree.parse(path).getroot()
        if svg.tag != NAMESPACE + "svg" or svg.attrib != {
            "width": "24", "height": "24", "viewBox": "0 0 24 24", "fill": "none",
        }:
            raise ValueError(f"Unexpected SVG root: {path.name}")
        ids = [element.attrib["id"] for element in svg.iter() if "id" in element.attrib]
        if len(ids) > 1:
            raise ValueError(f"Multiple SVG IDs: {path.name}")
        # Only the clipped icons need a client-compatible unique ID.
        preamble = (
            '"use client";\n\nimport { useId } from "react";\n\n' if ids else ""
        )
        setup = "  const clipId = useId();\n" if ids else ""
        shapes = "\n".join(jsx(child, 3, ids[0] if ids else None) for child in svg)
        component = (
            f"{HEADER}{preamble}"
            'import type { IconProps } from "../Icon.types.js";\n\n'
            f"export const {name} = (props: IconProps) => {{\n"
            '  const { size, width = size ?? "1em", height = size ?? "1em", ...svgProps } = props;\n'
            f"{setup}"
            "  return (\n"
            '    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none"\n'
            '      width={width} height={height} focusable="false"\n'
            '      aria-hidden={svgProps["aria-label"] || svgProps["aria-labelledby"] ? undefined : true}\n'
            '      {...svgProps}\n'
            "    >\n"
            f"{shapes}\n"
            "    </svg>\n"
            "  );\n"
            "};\n"
        )
        names.add(name)
        modules[slug] = (name, component)
    if not modules:
        raise ValueError(f"No SVGs found in {source}")

    directory = destination / "duotone"
    directory.mkdir(parents=True, exist_ok=True)
    for slug, (_, component) in modules.items():
        (directory / f"{slug}.tsx").write_text(component, encoding="utf-8")
    for previous in directory.glob("*.tsx"):
        if previous.stem not in modules and previous.read_text(encoding="utf-8").startswith(HEADER):
            previous.unlink()
    exports = "".join(
        f'export {{ {name} }} from "./duotone/{slug}.js";\n'
        for slug, (name, _) in sorted(modules.items())
    )
    (destination / "index.ts").write_text(
        HEADER + 'export type { IconComponent, IconProps } from "./Icon.types.js";\n' + exports,
        encoding="utf-8",
    )
    prettier = destination.parents[2] / "node_modules" / ".bin" / "prettier"
    subprocess.run(
        [str(prettier), "--write", "--log-level", "warn", str(directory / "*.tsx")],
        check=True,
    )
    print(f"Generated {len(modules)} icons")


if __name__ == "__main__":
    generate(Path(sys.argv[1]))
